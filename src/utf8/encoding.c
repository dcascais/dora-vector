bool dora_utf8_ascii_is_text_space(char value) {
    return value == ' ' || value == '\t' || value == '\r' || value == '\n';
}

int dora_utf8_encode(const uint32_t* scalars,
                     size_t scalar_count,
                     struct dora_mutable_bytes output,
                     size_t* out_input_scalar_count,
                     size_t* out_byte_count) {
    if ((scalar_count != 0 && scalars == nullptr) || !utf8_output_is_valid(output) ||
        out_input_scalar_count == nullptr || out_byte_count == nullptr) {
        return EINVAL;
    }
    size_t extent;
    if (ckd_mul(&extent, scalar_count, sizeof *scalars)) {
        return EOVERFLOW;
    }
    size_t input = 0, produced = 0;
    int status = 0;
    while (input < scalar_count) {
        if (produced == output.byte_count) {
            status = ENOBUFS;
            break;
        }
        uint8_t encoded[4];
        const size_t remaining = output.byte_count - produced;
        uint8_t* destination = remaining >= sizeof encoded ? output.data + produced : encoded;
        size_t size = 0;
        status = utf8_scalar_bytes(scalars[input], destination, &size);
        if (status != 0) {
            break;
        }
        if (size > remaining) {
            status = ENOBUFS;
            break;
        }
        if (remaining < sizeof encoded) {
            memcpy(output.data + produced, encoded, size);
        }
        produced += size;
        ++input;
    }
    *out_input_scalar_count = input;
    *out_byte_count = produced;
    return status;
}

int dora_utf8_decode(struct dora_bytes bytes,
                     uint32_t* out_scalars,
                     size_t scalar_capacity,
                     size_t* out_input_byte_count,
                     size_t* out_scalar_count) {
    if (!bytes_are_well_formed(bytes) || (scalar_capacity != 0 && out_scalars == nullptr) ||
        out_input_byte_count == nullptr || out_scalar_count == nullptr) {
        return EINVAL;
    }
    size_t extent;
    if (ckd_mul(&extent, scalar_capacity, sizeof *out_scalars)) {
        return EOVERFLOW;
    }
    size_t input = 0, produced = 0;
    int status = 0;
    while (input < bytes.byte_count) {
        if (produced == scalar_capacity) {
            status = ENOBUFS;
            break;
        }
        size_t size = 0;
        uint32_t scalar = 0;
        status = utf8_read_scalar((struct dora_bytes){bytes.data + input, bytes.byte_count - input}, &scalar, &size);
        if (status != 0) {
            break;
        }
        out_scalars[produced++] = scalar;
        input += size;
    }
    *out_input_byte_count = input;
    *out_scalar_count = produced;
    return status;
}

int dora_utf8_decode_utf16_scalar(const uint16_t* units,
                                  size_t utf16_unit_count,
                                  uint32_t* out_scalar,
                                  size_t* out_utf16_unit_count) {
    if ((utf16_unit_count != 0 && units == nullptr) || out_scalar == nullptr || out_utf16_unit_count == nullptr) {
        return EINVAL;
    }
    if (utf16_unit_count == 0) {
        return EAGAIN;
    }
    const uint32_t first = units[0];
    if (first >= 0xDC00 && first <= 0xDFFF) {
        return EILSEQ;
    }
    uint32_t scalar = first;
    size_t consumed = 1;
    if (first >= 0xD800 && first <= 0xDBFF) {
        if (utf16_unit_count == 1) {
            return EAGAIN;
        }
        const uint32_t second = units[1];
        if (second < 0xDC00 || second > 0xDFFF) {
            return EILSEQ;
        }
        scalar = 0x1'0000 + (first - 0xD800) * 0x400 + second - 0xDC00;
        consumed = 2;
    }
    *out_scalar = scalar;
    *out_utf16_unit_count = consumed;
    return 0;
}

